// Декомпозиция Данцига-Вульфа с генерацией столбцов.
//
// Матрица задачи блочная: если сгруппировать переменные по объектам, то
// ограничения каждого объекта (балансы по его интервалам, ёмкость ЗУ, лимиты
// времени) не пересекаются с ограничениями других объектов. Единственное, что
// связывает блоки, — передачи: объём, отправленный из i в j, входит и в баланс
// отправителя, и в баланс получателя.
//
// Переменная передачи дублируется: у отправителя x_out, у получателя x_in,
// а в главную задачу выносится связующее равенство x_out - x_in = 0.
//
// Главная задача выбирает веса планов блоков и возвращает блокам цены
// (двойственные оценки связующих равенств). Блок по этим ценам ищет свой
// наилучший план. Когда ни один блок не предлагает плана выгоднее уже
// найденных, решение оптимально.
#pragma once

#include <string>
#include <vector>

#include "lp.h"
#include "model.h"

namespace pdaplan {

struct DwOptions {
    // Разбиение по интервалам вместо разбиения по объектам. Блоком становится один
    // интервал постоянства структуры, а связывают блоки только остатки в
    // запоминающих устройствах на границах интервалов. Передачи при этом целиком
    // внутри блока, поэтому связующих ограничений кратно меньше.
    bool byInterval = false;
    int maxIterations = 500;
    double tolerance = 1e-7;
    bool verbose = false;
};

struct DwStats {
    int iterations = 0;
    int columnsGenerated = 0;
    int blocks = 0;
    int couplings = 0;
    double masterObjective = 0.0;
};

// Решает задачу методом Данцига-Вульфа. Возвращает решение в тех же
// переменных, что и монолитный решатель, чтобы работали checkSolution и buildPlan.
Solution solveDantzigWolfe(const Task& task, const DwOptions& options, DwStats& stats);

}  // namespace pdaplan